#!/usr/bin/env python3
"""Project library — front-matter index over the design documents.

Every markdown file under `docs/` and `.context/org/` (recursive, except the
generated `docs/LIBRARY.md`) opens with a YAML front-matter block:

    ---
    id: spec-2026-10-05-observability-and-trading-unblock
    type: spec            # spec | plan | report | research | charter | guide
    status: proposed      # proposed | accepted | built | shipped | superseded
                          # | historical | reference | living
    date: 2026-10-05
    supersedes: [spec-2026-09-25-multi-model-platform]
    superseded_by: null
    summary: >-
      One to three sentences, written from the document.
    ---

Commands (stdlib + pyyaml, no network):

    python scripts/lib.py index                      # regenerate docs/LIBRARY.md
    python scripts/lib.py show <id> [--section S]    # one doc, or one section
    python scripts/lib.py grep <term> [--max N]      # id §heading + paragraph
    python scripts/lib.py status <id>                # one line
    python scripts/lib.py check                      # the lint (exit 2 on FAIL)

`--root` points at a repo root other than this checkout (tests use it).
Exit codes: 0 ok, 1 usage / unknown id, 2 `check` failed. `index` and
`check` end with a `LIB <CMD> OK|FAIL` verdict line; the read commands print
content only and a `LIB <CMD> FAIL: ...` line on error.

Id conventions (enforced by `check`):
  spec/plan/report/research  ->  <type>-<YYYY-MM-DD>-<slug>
  charter/guide              ->  <type>-<slug>
Specs and plans under docs/superpowers must use their filename stem as the
slug (specs drop a trailing `-design`).
"""

from __future__ import annotations

import argparse
import datetime as _dt
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

TYPES = ("spec", "plan", "report", "charter", "guide", "research")
STATUSES = (
    "proposed", "accepted", "built", "shipped", "superseded",
    "historical", "reference", "living",
)
REQUIRED_KEYS = ("id", "type", "status", "date", "summary")
DATED_ID = re.compile(r"^[a-z]+-[0-9]{4}-[0-9]{2}-[0-9]{2}-[a-z0-9-]+$")
UNDATED_ID = re.compile(r"^(charter|guide)-[a-z0-9-]+$")
SCAN_DIRS = ("docs", ".context/org")
LIBRARY_REL = "docs/LIBRARY.md"
FOOTER = "<!-- generated by scripts/lib.py index; do not hand-edit -->"
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
DEFAULT_GREP_MAX = 20


@dataclass
class Doc:
    path: Path
    rel: str
    fm: dict | None
    body: str
    errors: list[str] = field(default_factory=list)
    summary_lines: list[str] = field(default_factory=list)  # raw YAML lines of `summary:` (hyphen-wrap check)

    @property
    def id(self) -> str | None:
        return self.fm.get("id") if isinstance(self.fm, dict) else None


# ── loading ──────────────────────────────────────────────────────────────────

def repo_root_default() -> Path:
    return Path(__file__).resolve().parent.parent


def iter_doc_paths(root: Path) -> list[Path]:
    skip = (root / LIBRARY_REL).resolve()
    out: list[Path] = []
    for rel in SCAN_DIRS:
        base = root / rel
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*.md")):
            if p.resolve() == skip:
                continue
            out.append(p)
    return out


def split_front_matter(text: str) -> tuple[str | None, str, str | None]:
    """Return (yaml_text, body, error). yaml_text is None when absent."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text, "no front-matter block (file must start with `---`)"
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return "\n".join(lines[1:i]), "\n".join(lines[i + 1:]), None
    return None, text, "unterminated front-matter block"


def load_doc(root: Path, path: Path) -> Doc:
    rel = path.relative_to(root).as_posix()
    text = path.read_text(encoding="utf-8")
    yaml_text, body, err = split_front_matter(text)
    doc = Doc(path=path, rel=rel, fm=None, body=body)
    if err:
        doc.errors.append(err)
        return doc
    try:
        fm = yaml.safe_load(yaml_text)
    except yaml.YAMLError as exc:  # pragma: no cover - exercised by check
        doc.errors.append(f"front-matter does not parse: {exc}")
        return doc
    if not isinstance(fm, dict):
        doc.errors.append(f"front-matter is {type(fm).__name__}, not a mapping")
        return doc
    if isinstance(fm.get("date"), (_dt.date, _dt.datetime)):
        fm["date"] = fm["date"].isoformat()[:10]
    doc.fm = fm
    in_summary = False
    for line in yaml_text.split("\n"):
        if line.startswith("summary:"):
            in_summary = True
            continue
        if in_summary:
            if line.startswith((" ", "\t")):
                doc.summary_lines.append(line)
            else:
                in_summary = False
    return doc


def load_docs(root: Path) -> list[Doc]:
    return [load_doc(root, p) for p in iter_doc_paths(root)]


def by_id(docs: list[Doc]) -> dict[str, Doc]:
    out: dict[str, Doc] = {}
    for d in docs:
        if d.id and d.id not in out:
            out[d.id] = d
    return out


# ── validation ───────────────────────────────────────────────────────────────

def _expected_superpowers_id(doc: Doc) -> str | None:
    """For docs/superpowers/{specs,plans}/<stem>.md the id is fixed by the stem."""
    parts = doc.rel.split("/")
    if len(parts) == 4 and parts[:2] == ["docs", "superpowers"]:
        stem = doc.path.stem
        if parts[2] == "specs":
            if stem.endswith("-design"):
                stem = stem[: -len("-design")]
            return f"spec-{stem}"
        if parts[2] == "plans":
            return f"plan-{stem}"
    return None


def validate_docs(docs: list[Doc]) -> list[str]:
    findings: list[str] = []
    seen: dict[str, str] = {}
    for d in docs:
        for e in d.errors:
            findings.append(f"{d.rel}: {e}")
        if d.fm is None:
            continue
        if any(line.rstrip().endswith("-") for line in d.summary_lines):
            findings.append(f"{d.rel}: a summary line ends with `-` (YAML folds it as `word- next`; re-wrap)")
        fm = d.fm
        missing = [k for k in REQUIRED_KEYS if k not in fm or fm[k] in (None, "")]
        if missing:
            findings.append(f"{d.rel}: missing front-matter key(s) {', '.join(missing)}")
        typ, status, did = fm.get("type"), fm.get("status"), fm.get("id")
        if typ not in TYPES:
            findings.append(f"{d.rel}: type `{typ}` not in {list(TYPES)}")
        if status not in STATUSES:
            findings.append(f"{d.rel}: status `{status}` not in {list(STATUSES)}")
        date = fm.get("date")
        if date is not None:
            try:
                _dt.date.fromisoformat(str(date))
            except ValueError:
                findings.append(f"{d.rel}: date `{date}` is not YYYY-MM-DD")
        if isinstance(did, str):
            if typ in ("charter", "guide"):
                if not UNDATED_ID.match(did) or not did.startswith(f"{typ}-"):
                    findings.append(f"{d.rel}: id `{did}` must match `{typ}-<slug>`")
            elif typ in TYPES:
                if not DATED_ID.match(did) or not did.startswith(f"{typ}-"):
                    findings.append(
                        f"{d.rel}: id `{did}` must match `{typ}-<YYYY-MM-DD>-<slug>`")
            exp = _expected_superpowers_id(d)
            if exp and did != exp:
                findings.append(f"{d.rel}: id `{did}` must be `{exp}` (filename stem)")
            if did in seen:
                findings.append(f"{d.rel}: duplicate id `{did}` (also {seen[did]})")
            else:
                seen[did] = d.rel
        elif did is not None:
            findings.append(f"{d.rel}: id must be a string")
        sup = fm.get("supersedes", [])
        if sup is None:
            sup = []
        if not isinstance(sup, list) or not all(isinstance(x, str) for x in sup):
            findings.append(f"{d.rel}: `supersedes` must be a list of ids")
        sby = fm.get("superseded_by")
        if sby is not None and not isinstance(sby, str):
            findings.append(f"{d.rel}: `superseded_by` must be an id or null")
        summary = fm.get("summary")
        if summary is not None and not isinstance(summary, str):
            findings.append(f"{d.rel}: `summary` must be a string")

    index = by_id(docs)
    for d in docs:
        if d.fm is None or not isinstance(d.id, str):
            continue
        sup = d.fm.get("supersedes") or []
        sby = d.fm.get("superseded_by")
        status = d.fm.get("status")
        if isinstance(sup, list):
            for x in sup:
                if not isinstance(x, str):
                    continue
                if x not in index:
                    findings.append(f"{d.rel}: supersedes unknown id `{x}`")
                elif index[x].fm.get("superseded_by") != d.id:
                    findings.append(
                        f"{d.rel}: supersedes `{x}` but that doc's superseded_by is "
                        f"`{index[x].fm.get('superseded_by')}`")
        if isinstance(sby, str):
            if sby not in index:
                findings.append(f"{d.rel}: superseded_by unknown id `{sby}`")
            else:
                other = index[sby].fm.get("supersedes") or []
                if d.id not in other:
                    findings.append(
                        f"{d.rel}: superseded_by `{sby}` but that doc's supersedes "
                        f"list does not name `{d.id}`")
            if status != "superseded":
                findings.append(
                    f"{d.rel}: has superseded_by but status is `{status}`, not `superseded`")
        elif status == "superseded":
            findings.append(f"{d.rel}: status superseded but superseded_by is null")
    return findings


# ── index ────────────────────────────────────────────────────────────────────

INDEX_SUMMARY_CHARS = 220


def _brief(text: str, limit: int = INDEX_SUMMARY_CHARS) -> str:
    """First sentence(s) of a summary, cut at a word boundary near `limit`,
    so docs/LIBRARY.md stays small enough to load every session; the full
    summary lives in the document's front-matter (`lib.py status <id>`)."""
    text = " ".join(str(text).split())
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:")
    return cut + " …"



def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render_library(docs: list[Doc]) -> str:
    good = [d for d in docs if d.fm is not None and isinstance(d.id, str)]
    lines = [
        "# Library — design documents",
        "",
        "Generated index of every document under `docs/` and `.context/org/`. "
        "Each document carries YAML front-matter with a stable `id` "
        "(`<type>-<date>-<slug>`, or `<type>-<slug>` for charters and guides), "
        "a `type`, a `status` and its supersession links.",
        "",
        "Statuses: `proposed` (written, not approved) · `accepted` (approved, not "
        "built) · `built` (code exists, not necessarily deployed) · `shipped` "
        "(deployed / in force) · `superseded` (replaced; row struck through with "
        "`→ <successor>`) · `historical` (record of a past state, not current) · "
        "`reference` (kept as a reference, no implementation status) · `living` "
        "(maintained continuously).",
        "",
        "Use `python scripts/lib.py status <id>` to check whether a document is "
        "current, and `python scripts/lib.py show <id> --section <n|heading>` to "
        "read one section without loading the whole file. Cite a document as "
        "`lib: <id> §<heading>`.",
        "",
    ]
    titles = {
        "spec": "Specs", "plan": "Plans", "report": "Reports",
        "charter": "Charters", "guide": "Guides", "research": "Research",
    }
    for typ in TYPES:
        rows = [d for d in good if d.fm.get("type") == typ]
        if not rows:
            continue
        rows.sort(key=lambda d: (str(d.fm.get("date", "")), d.id), reverse=True)
        lines.append(f"## {titles[typ]} ({len(rows)})")
        lines.append("")
        if typ == "research":
            lines.append(
                "Deep index for the LLM landscape set: "
                "`docs/research/llm-landscape-2026-09/00-comparison-matrix.md`.")
            lines.append("")
        lines.append("| id | status | date | summary | path |")
        lines.append("|---|---|---|---|---|")
        for d in rows:
            fm = d.fm
            ident = f"`{d.id}`"
            limit = 100 if typ == "research" else INDEX_SUMMARY_CHARS
            if fm.get("superseded_by"):
                ident = f"~~`{d.id}`~~ → `{fm['superseded_by']}`"
            lines.append(
                f"| {ident} | {fm.get('status', '')} | {fm.get('date', '')} | "
                f"{_cell(_brief(fm.get('summary', ''), limit))} | `{d.rel}` |")
        lines.append("")
    lines.append(FOOTER)
    return "\n".join(lines) + "\n"


# ── sections / grep ──────────────────────────────────────────────────────────

def _headings(body: str) -> list[tuple[int, int, str]]:
    """(line_index, level, text) for every heading outside fenced code."""
    out: list[tuple[int, int, str]] = []
    in_fence = False
    for i, line in enumerate(body.split("\n")):
        stripped = line.lstrip()
        if stripped.startswith("```") or stripped.startswith("~~~"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = HEADING_RE.match(line)
        if m:
            out.append((i, len(m.group(1)), m.group(2)))
    return out


def _heading_matches(text: str, wanted: str) -> bool:
    w = wanted.strip()
    if re.fullmatch(r"\d+[a-z]?", w):
        return re.match(rf"^{re.escape(w)}(?![0-9a-z])", text, flags=re.I) is not None
    return w.lower() in text.lower()


def extract_section(body: str, wanted: str) -> str | None:
    heads = _headings(body)
    lines = body.split("\n")
    for n, (idx, level, text) in enumerate(heads):
        if not _heading_matches(text, wanted):
            continue
        end = len(lines)
        for idx2, level2, _ in heads[n + 1:]:
            if level2 <= level:
                end = idx2
                break
        return "\n".join(lines[idx:end]).rstrip("\n") + "\n"
    return None


def grep_docs(docs: list[Doc], term: str, limit: int) -> list[tuple[str, str, str]]:
    """(id, nearest heading, paragraph) for each matching paragraph."""
    needle = term.lower()
    hits: list[tuple[str, str, str]] = []
    for d in docs:
        if d.fm is None or not isinstance(d.id, str):
            continue
        heads = _headings(d.body)
        lines = d.body.split("\n")
        heading = "(top)"
        hi = 0
        para: list[str] = []

        def flush(end: int) -> None:
            nonlocal para
            if para:
                text = "\n".join(para)
                if needle in text.lower():
                    hits.append((d.id, heading, text))
            para = []

        for i, line in enumerate(lines):
            while hi < len(heads) and heads[hi][0] <= i:
                heading = heads[hi][2]
                hi += 1
            if hi and heads[hi - 1][0] == i:
                flush(i)
                continue
            if line.strip() == "":
                flush(i)
                continue
            para.append(line)
        flush(len(lines))
        if len(hits) >= limit:
            break
    return hits[:limit]


# ── commands ─────────────────────────────────────────────────────────────────

def cmd_index(root: Path) -> int:
    docs = load_docs(root)
    findings = validate_docs(docs)
    out = root / LIBRARY_REL
    out.write_text(render_library(docs), encoding="utf-8")
    n = sum(1 for d in docs if d.fm is not None)
    for f in findings:
        print(f"warning: {f}")
    print(f"LIB INDEX OK ({n} docs -> {LIBRARY_REL})")
    return 0


def cmd_check(root: Path) -> int:
    docs = load_docs(root)
    findings = validate_docs(docs)
    if not docs:
        findings.append("0 docs scanned under docs/ and .context/org/ — nothing to check (wrong --root?)")
    lib = root / LIBRARY_REL
    if not lib.exists():
        findings.append(f"{LIBRARY_REL} missing (run `python scripts/lib.py index`)")
    elif lib.read_text(encoding="utf-8") != render_library(docs):
        findings.append(f"{LIBRARY_REL} is stale (run `python scripts/lib.py index`)")
    for f in findings:
        print(f)
    if findings:
        print(f"LIB CHECK FAIL ({len(findings)} findings)")
        return 2
    print("LIB CHECK OK")
    return 0


def _lookup(root: Path, ident: str, cmd: str) -> Doc | None:
    docs = load_docs(root)
    d = by_id(docs).get(ident)
    if d is None:
        print(f"LIB {cmd.upper()} FAIL: unknown id `{ident}`")
    return d


def cmd_show(root: Path, ident: str, section: str | None) -> int:
    d = _lookup(root, ident, "show")
    if d is None:
        return 1
    if section is None:
        sys.stdout.write(d.body if d.body.endswith("\n") else d.body + "\n")
        return 0
    text = extract_section(d.body, section)
    if text is None:
        print(f"LIB SHOW FAIL: no heading matching `{section}` in `{ident}`")
        return 1
    sys.stdout.write(text)
    return 0


def cmd_status(root: Path, ident: str) -> int:
    d = _lookup(root, ident, "status")
    if d is None:
        return 1
    fm = d.fm
    bits = [f"{ident}: {fm.get('status')}"]
    if fm.get("superseded_by"):
        bits.append(f"— superseded by {fm['superseded_by']}")
    if fm.get("supersedes"):
        bits.append(f"— supersedes {', '.join(fm['supersedes'])}")
    bits.append(f"({fm.get('type')}, {fm.get('date')}, {d.rel})")
    print(" ".join(bits))
    return 0


def cmd_grep(root: Path, term: str, limit: int) -> int:
    hits = grep_docs(load_docs(root), term, limit)
    for ident, heading, para in hits:
        print(f"{ident} §{heading}")
        print(para)
        print()
    if not hits:
        print(f"LIB GREP FAIL: no paragraph matches `{term}`")
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    class _Parser(argparse.ArgumentParser):
        def error(self, message):  # usage errors are exit 1; 2 is reserved for `check` FAIL
            self.print_usage(sys.stderr)
            print(f"LIB USAGE FAIL: {message}", file=sys.stderr)
            raise SystemExit(1)

    ap = _Parser(prog="lib.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=repo_root_default(),
                    help="repo root (default: parent of scripts/)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("index", help="regenerate docs/LIBRARY.md")
    sub.add_parser("check", help="lint front-matter + index freshness")
    p = sub.add_parser("show", help="print one document or one section")
    p.add_argument("id")
    p.add_argument("--section", "-s", default=None,
                   help="section number (`12`) or case-insensitive heading substring")
    p = sub.add_parser("status", help="one-line status for an id")
    p.add_argument("id")
    p = sub.add_parser("grep", help="case-insensitive paragraph search")
    p.add_argument("term")
    p.add_argument("--max", type=int, default=DEFAULT_GREP_MAX)
    args = ap.parse_args(argv)
    root = args.root.resolve()
    if args.cmd == "index":
        return cmd_index(root)
    if args.cmd == "check":
        return cmd_check(root)
    if args.cmd == "show":
        return cmd_show(root, args.id, args.section)
    if args.cmd == "status":
        return cmd_status(root, args.id)
    if args.cmd == "grep":
        return cmd_grep(root, args.term, args.max)
    return 1  # pragma: no cover


if __name__ == "__main__":
    sys.exit(main())
